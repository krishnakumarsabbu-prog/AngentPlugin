import React, { useState, useMemo } from "react";
import { Copy, Check, X, FileText, Code } from "lucide-react";
import type { AgentBuilderFormState } from "./types";
import { builderStateToAgent } from "./types";
import type { AgentExportFormat } from "../../../types";

interface AgentPreviewModalProps {
  state: AgentBuilderFormState;
  isOpen: boolean;
  onClose: () => void;
  onToast: (msg: string, tone?: "success" | "error") => void;
}

export const AgentPreviewModal: React.FC<AgentPreviewModalProps> = ({
  state,
  isOpen,
  onClose,
  onToast,
}) => {
  const [format, setFormat] = useState<AgentExportFormat>("agent-spec");
  const [copied, setCopied] = useState(false);

  const previewContent = useMemo(() => {
    const agent = builderStateToAgent(state);

    if (format === "copilot-instructions") {
      const lines: string[] = [];
      lines.push(`<!-- Generated by AgentForge: ${agent.name || "Custom Agent"} v${agent.version || "1.0.0"} -->`);
      lines.push(`# ${agent.name || "Agent"}`);
      lines.push("");
      if (agent.role) lines.push(`**Role:** ${agent.role}\n`);
      if (agent.description) lines.push(`> ${agent.description}\n`);
      if (agent.objective) lines.push(`## Objective\n${agent.objective}\n`);
      if (agent.instructions) lines.push(`## Instructions\n${agent.instructions}\n`);
      if (agent.scope || agent.outOfScope) {
        lines.push("## Scope & Boundaries");
        if (agent.scope) lines.push(`**In-Scope:** ${agent.scope}`);
        if (agent.outOfScope) lines.push(`**Out-of-Scope:** ${agent.outOfScope}`);
        lines.push("");
      }
      if (agent.operatingPrinciples && agent.operatingPrinciples.length > 0) {
        lines.push("## Operating Principles");
        for (const p of agent.operatingPrinciples) lines.push(`- ${p}`);
        lines.push("");
      }
      if (agent.assignedSkillIds && agent.assignedSkillIds.length > 0) {
        lines.push("## Assigned Skills");
        for (const s of agent.assignedSkillIds) lines.push(`- \`${s}\``);
        lines.push("");
      }
      if (agent.permissionPolicy) {
        lines.push("## Security & Permission Guardrails");
        lines.push(`- **Read-Only:** ${agent.permissionPolicy.readOnly ?? true}`);
        lines.push(`- **Workspace Access:** ${agent.permissionPolicy.workspaceAccess ?? true}`);
        lines.push(`- **Write Operations:** ${agent.permissionPolicy.writeOperations ?? false}`);
        lines.push(`- **Shell Execution:** ${agent.permissionPolicy.shell ? "Allowed" : "Forbidden"}`);
        lines.push(`- **Network Access:** ${agent.permissionPolicy.network ? "Allowed" : "Forbidden"}`);
        lines.push("");
      }
      return lines.join("\n");
    }

    if (format === "claude-subagent") {
      const lines: string[] = [];
      lines.push(`<agent id="${agent.id || "agent"}" version="${agent.version || "1.0.0"}">`);
      lines.push(`  <name>${agent.name || "Agent"}</name>`);
      lines.push(`  <role>${agent.role || ""}</role>`);
      lines.push(`  <objective>${agent.objective || ""}</objective>`);
      lines.push("");
      lines.push("  <system_instructions>");
      lines.push(agent.instructions || "");
      lines.push("  </system_instructions>");
      lines.push("");
      if (agent.operatingPrinciples && agent.operatingPrinciples.length > 0) {
        lines.push("  <operating_principles>");
        for (const p of agent.operatingPrinciples) lines.push(`    <principle>${p}</principle>`);
        lines.push("  </operating_principles>");
        lines.push("");
      }
      if (agent.toolDefinitions && agent.toolDefinitions.length > 0) {
        lines.push("  <declared_tools>");
        for (const t of agent.toolDefinitions) {
          lines.push(`    <tool id="${t.id}" availability="${t.availability || "always"}">`);
          lines.push(`      <name>${t.name}</name>`);
          lines.push(`      <purpose>${t.purpose || t.description}</purpose>`);
          lines.push("    </tool>");
        }
        lines.push("  </declared_tools>");
        lines.push("");
      }
      lines.push("</agent>");
      return lines.join("\n");
    }

    if (format === "openai-assistant") {
      const payload = {
        name: agent.name,
        instructions: agent.instructions,
        tools: (agent.toolDefinitions || []).map((t) => ({
          type: "function",
          function: {
            name: t.id.replace(/-/g, "_"),
            description: t.description,
            parameters: t.schema || { type: "object", properties: {} },
          },
        })),
        metadata: {
          id: agent.id,
          role: agent.role,
          version: agent.version,
        },
      };
      return JSON.stringify(payload, null, 2);
    }

    // Default: agent-spec
    return JSON.stringify(agent, null, 2);
  }, [state, format]);

  if (!isOpen) return null;

  const handleCopy = () => {
    navigator.clipboard.writeText(previewContent).then(() => {
      setCopied(true);
      onToast("Agent preview copied to clipboard", "success");
      setTimeout(() => setCopied(false), 2000);
    });
  };

  return (
    <div
      style={{
        position: "fixed",
        top: 0,
        left: 0,
        right: 0,
        bottom: 0,
        background: "rgba(15, 23, 42, 0.6)",
        backdropFilter: "blur(4px)",
        display: "flex",
        alignItems: "center",
        justifyContent: "center",
        zIndex: 1000,
        padding: "20px",
      }}
      onClick={onClose}
    >
      <div
        style={{
          background: "var(--surface)",
          borderRadius: "var(--radius-lg)",
          width: "100%",
          maxWidth: "800px",
          maxHeight: "85vh",
          display: "flex",
          flexDirection: "column",
          boxShadow: "var(--shadow-md)",
          border: "1px solid var(--border)",
          overflow: "hidden",
        }}
        onClick={(e) => e.stopPropagation()}
      >
        {/* Modal Header */}
        <div
          style={{
            padding: "14px 18px",
            borderBottom: "1px solid var(--border)",
            display: "flex",
            justifyContent: "space-between",
            alignItems: "center",
            background: "var(--surface-alt)",
          }}
        >
          <div>
            <h3 style={{ margin: 0, fontSize: "14px", fontWeight: 600 }}>
              Live Agent Configuration Preview
            </h3>
            <span style={{ fontSize: "11px", color: "var(--text-secondary)" }}>
              {state.name || "Untitled Agent"} (v{state.version || "1.0.0"})
            </span>
          </div>

          <div style={{ display: "flex", alignItems: "center", gap: "8px" }}>
            <button
              type="button"
              className="btn btn-secondary btn-sm"
              onClick={handleCopy}
              style={{ display: "flex", alignItems: "center", gap: "6px" }}
            >
              {copied ? <Check size={14} style={{ color: "var(--success)" }} /> : <Copy size={14} />}
              {copied ? "Copied" : "Copy"}
            </button>
            <button
              type="button"
              className="btn btn-icon btn-ghost"
              onClick={onClose}
            >
              <X size={16} />
            </button>
          </div>
        </div>

        {/* Format Selector Bar */}
        <div
          style={{
            display: "flex",
            gap: "8px",
            padding: "8px 18px",
            borderBottom: "1px solid var(--border)",
            background: "var(--surface)",
          }}
        >
          {[
            { id: "agent-spec", label: "Agent Spec (JSON)" },
            { id: "copilot-instructions", label: "Copilot Instructions (MD)" },
            { id: "claude-subagent", label: "Claude Subagent (XML/MD)" },
            { id: "openai-assistant", label: "OpenAI Assistant (JSON)" },
          ].map((item) => (
            <button
              key={item.id}
              type="button"
              className={`btn btn-sm ${format === item.id ? "btn-primary" : "btn-ghost"}`}
              style={{ fontSize: "11px", height: "26px", padding: "0 10px" }}
              onClick={() => setFormat(item.id as AgentExportFormat)}
            >
              {item.label}
            </button>
          ))}
        </div>

        {/* Code Content */}
        <div style={{ flex: 1, overflowY: "auto", padding: "16px", background: "#0F172A" }}>
          <pre
            style={{
              margin: 0,
              fontFamily: "var(--font-mono)",
              fontSize: "12px",
              color: "#E2E8F0",
              lineHeight: 1.5,
              whiteSpace: "pre-wrap",
              wordBreak: "break-all",
            }}
          >
            {previewContent}
          </pre>
        </div>
      </div>
    </div>
  );
};
